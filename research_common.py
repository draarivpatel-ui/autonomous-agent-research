"""Shared reporting utilities. Reports exclude hostnames, usernames and home paths."""
from __future__ import annotations

import csv
import hashlib
import importlib.metadata
import importlib.util
import json
import platform
import sys
import socket
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent


@contextmanager
def offline_network_counter():
    """Count and deny network attempts during a local benchmark run."""
    counter = {"attempts": 0}
    def deny(*args, **kwargs):
        counter["attempts"] += 1
        raise RuntimeError("Network disabled during offline evaluation")
    original = (socket.socket.connect, socket.socket.connect_ex,
                socket.socket.sendto, socket.getaddrinfo)
    socket.socket.connect = socket.socket.connect_ex = socket.socket.sendto = deny
    socket.getaddrinfo = deny
    try:
        yield counter
    finally:
        socket.socket.connect, socket.socket.connect_ex, socket.socket.sendto, socket.getaddrinfo = original


def source_file(repo: str, filename: str) -> Path:
    live = ROOT.parent / "repos" / repo / filename
    vendored = ROOT / "verified_sources" / repo / filename
    return live if live.is_file() else vendored


def load_module(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"Missing module {name}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def environment() -> dict:
    return {
        "system": platform.system(), "architecture": platform.machine(),
        "python": platform.python_version(),
        "dependencies": {name: importlib.metadata.version(name) for name in
                         ("numpy", "z3-solver", "cryptography")},
    }


def latency(values: list[float]) -> dict:
    return {"median_ms": float(np.median(values)), "p95_ms": float(np.percentile(values, 95)),
            "total_ms": float(sum(values))}


def markdown_table(rows: list[dict]) -> str:
    if not rows:
        return "No measurements were collected.\n"
    names = list(rows[0])
    def fmt(value):
        if isinstance(value, float):
            return f"{value:.6f}"
        return str(value).replace("|", "/").replace("\n", " ")
    return "| " + " | ".join(names) + " |\n| " + " | ".join(["---"] * len(names)) + " |\n" + \
        "\n".join("| " + " | ".join(fmt(row.get(key, "")) for key in names) + " |" for row in rows) + "\n"


def write_results(output: Path, study: str, rows: list[dict], *,
                  metadata: dict | None = None, details: list | dict | None = None) -> dict:
    output.mkdir(parents=True, exist_ok=True)
    report = {
        "schema_version": 1, "study": study,
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "environment": environment(), "metadata": {**(metadata or {}), "common_source_sha256": sha256(Path(__file__))},
        "summary": rows, "details": details if details is not None else [],
    }
    (output / "results.json").write_text(json.dumps(report, indent=2, allow_nan=False) + "\n")
    if rows:
        with (output / "summary.csv").open("w", newline="") as stream:
            writer = csv.DictWriter(stream, fieldnames=list(rows[0]), lineterminator="\n")
            writer.writeheader()
            writer.writerows(rows)
    (output / "RESULTS.md").write_text(
        "# Empirical measurements\n\nGenerated by executing the benchmark. "
        "Runtime measurements are hardware-dependent.\n\n" + markdown_table(rows))
    return report
